class LanguageSystem {
    constructor() {
        this.currentLang = localStorage.getItem('sirius_lang') || 'en';
        this.langButtons = document.querySelectorAll('.lang-btn');
        this.init();
    }

    init() {
        this.updateUI(this.currentLang);
        this.bindEvents();
    }

    bindEvents() {
        this.langButtons.forEach(btn => {
            btn.addEventListener('click', () => {
                const lang = btn.id.replace('lang-', '');
                if (translations[lang] && Object.keys(translations[lang]).length > 0) {
                    this.switchLanguage(lang);
                }
            });
        });
    }

    switchLanguage(lang) {
        if (lang === this.currentLang) return;

        this.currentLang = lang;
        localStorage.setItem('sirius_lang', lang);

        // Dynamic transitions
        document.body.style.opacity = '0';

        setTimeout(() => {
            this.updateUI(lang);
            this.handleRTL(lang);
            document.body.style.opacity = '1';
        }, 150);
    }

    updateUI(lang) {
        const langData = translations[lang];

        // Update all elements with data-i18n attribute
        document.querySelectorAll('[data-i18n]').forEach(element => {
            const key = element.getAttribute('data-i18n');
            if (langData[key]) {
                if (element.tagName === 'INPUT' || element.tagName === 'TEXTAREA') {
                    element.placeholder = langData[key];
                } else if (element.tagName === 'META') {
                    element.setAttribute('content', langData[key]);
                } else {
                    if (typeof langData[key] === 'string' && langData[key].includes('<') && langData[key].includes('>')) {
                        element.innerHTML = langData[key];
                    } else {
                        element.textContent = langData[key];
                    }
                }
            }
        });

        // Update placeholders specifically
        document.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
            const key = element.getAttribute('data-i18n-placeholder');
            if (langData[key]) element.placeholder = langData[key];
        });

        // Update titles/aria-labels
        document.querySelectorAll('[aria-label][data-i18n-label]').forEach(element => {
            const key = element.getAttribute('data-i18n-label');
            if (langData[key]) element.setAttribute('aria-label', langData[key]);
        });

        document.querySelectorAll('[title][data-i18n-title]').forEach(element => {
            const key = element.getAttribute('data-i18n-title');
            if (langData[key]) element.title = langData[key];
        });

        // Update active class on buttons
        this.langButtons.forEach(btn => {
            btn.classList.toggle('active', btn.id === `lang-${lang}`);
        });

        // Update document lang attribute
        document.documentElement.lang = lang;
    }

    handleRTL(lang) {
        if (lang === 'ar') {
            document.body.dir = 'rtl';
            document.body.classList.add('rtl-mode');
        } else {
            document.body.dir = 'ltr';
            document.body.classList.remove('rtl-mode');
        }
    }
}


class CEOVideoSystem {
    constructor() {
        this.container = document.getElementById('ceo-video-container');
        this.closeBtn = document.getElementById('ceo-video-close');
        this.player = document.getElementById('ceo-video-player');
        this.source = document.getElementById('ceo-video-source');
        this.avatar = document.querySelector('.ai-ceo-avatar');
        this.indicator = this.avatar ? this.avatar.querySelector('.status-indicator') : null;
        this.autoCloseTimer = null;

        if (this.container && this.avatar) {
            this.init();
        }
    }

    init() {
        this.avatar.addEventListener('click', (e) => {
            e.stopPropagation();
            this.toggle();
        });

        if (this.closeBtn) {
            this.closeBtn.addEventListener('click', (e) => {
                e.stopPropagation();
                this.hide();
            });
        }

        if (this.player) {
            this.player.addEventListener('ended', () => {
                this.autoCloseTimer = setTimeout(() => {
                    this.hide();
                }, 3000);
            });
        }

        // Listen for language changes via buttons
        document.querySelectorAll('.lang-btn').forEach(btn => {
            btn.addEventListener('click', () => {
                const lang = btn.id.replace('lang-', '');
                this.updateSource(lang);
            });
        });

        // initial set based on current language
        setTimeout(() => {
            const currentLang = document.documentElement.lang || 'tr';
            this.updateSource(currentLang);
        }, 100);

        // Mark as active
        if (this.indicator) {
            this.indicator.classList.remove('inactive');
            this.indicator.classList.add('active');
        }

        // Close when clicking outside
        document.addEventListener('click', (e) => {
            if (this.container.classList.contains('active') && !this.container.contains(e.target) && !this.avatar.contains(e.target)) {
                this.hide();
            }
        });
    }

    toggle() {
        if (this.container.classList.contains('active')) {
            this.hide();
        } else {
            this.show();
        }
    }

    show() {
        if (!this.container || !this.player) return;
        clearTimeout(this.autoCloseTimer);
        this.container.classList.add('active');
        document.body.classList.add('video-active'); // For hero text sliding
        if (this.player.paused) {
            this.player.play().catch(err => {
                console.log("Auto-play blocked or source missing.");
            });
        }
    }

    hide() {
        if (!this.container || !this.player) return;
        clearTimeout(this.autoCloseTimer);
        this.container.classList.remove('active');
        document.body.classList.remove('video-active'); // Revert hero text
        this.player.pause();
    }

    updateSource(lang) {
        if (!this.source || !this.player) return;
        const newSrc = `assets/videos/${lang}/ceo.mp4`;
        if (this.source.getAttribute('src') !== newSrc) {
            this.source.setAttribute('src', newSrc);
            this.player.load();
            // If already active, play the new one
            if (this.container.classList.contains('active')) {
                clearTimeout(this.autoCloseTimer);
                this.player.play().catch(e => { });
            }
        }
    }
}

